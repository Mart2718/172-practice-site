#!/usr/bin/env python3
"""Write BLUEPRINT.md: for each standard, the kinds of problem the pool makes and one sample question per family.

    python3 generators/blueprint.py            # rewrites BLUEPRINT.md from bank/ and site/pool/

Questions only, no answers. It reads the exported pool, so run it after generators/pool.py.
"""
import json
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from packet import to_md  # noqa: E402

POOL = os.path.join(ROOT, "site", "pool")
TIER = {"floor": "Core practice", "assessment": "Putting it together", "slip": "Spot the slip", "bridge": "Looking ahead to calculus"}
NEW = [f"EL{i}" for i in range(1, 8)] + ["PF2", "PF3"] + [f"TE{i}" for i in range(1, 7)] + [f"PR{i}" for i in range(3, 10)]


def tidy(s):
    s = re.sub(r"<table.*?</table>", "[a table of values]", s, flags=re.S)
    t = to_md(s.replace("\\allowbreak ", "").replace("\\allowbreak", "").replace("$", r"\$")).replace("\n", " ")
    return re.sub(r"(^|\s)>\s+", " ", t).strip()


def main():
    index = {s["code"]: s for s in json.load(open(os.path.join(POOL, "index.json")))["standards"]}
    out = ["# Blueprint: the Chapter 3–5 practice problems", "",
           "What each of the 22 standards that were added after Chapter 1 and 2 asks students to do. One section per standard; one row per problem family "
           "(a family is one template, up to 12 versions with different numbers). Generated by `generators/blueprint.py`; do not edit by hand.", "",
           "**Tiers.** *Core practice* is the skill on its own. *Putting it together* combines it with earlier skills or asks for a justification.", "",
           "| Standard | Exam | Families | Items |", "|---|---|---|---|"]
    for code in NEW:
        s = index[code]
        out.append(f"| [{code}](#{code.lower()}) {s['title']} | {s['exam']} | {s['families']} | {s['items']} |")
    out.append("")
    for code in NEW:
        s = index[code]
        bank = next(yaml.safe_load(open(os.path.join(ROOT, "bank", sub, f"{code}.yaml")))
                    for sub in ("ch3", "ch4", "ch5") if os.path.exists(os.path.join(ROOT, "bank", sub, f"{code}.yaml")))
        pool = json.load(open(os.path.join(POOL, f"{code}.json")))
        first = {}
        for it in pool["items"]:
            first.setdefault(it["family"], it)
        out += [f"## {code}", "", f"**{s['title']}** · {s['exam']} · Chapter {s['chapter']}", "", bank.get("objective", s.get("blurb", "")), "",
                "| Family | Tier | Item type | Template | Sample question |", "|---|---|---|---|---|"]
        for p in bank["problems"]:
            it = first.get(p["id"])
            if not it:
                continue
            types = p["item_type"] if isinstance(p["item_type"], list) else [p["item_type"]]
            qs = " ".join(filter(None, [tidy(it["stem"])] + [f"({chr(97 + k)}) {tidy(part['q'])}" for k, part in enumerate(it["parts"])]))
            out.append(f"| {p['id']} | {TIER.get(p['tier'], p['tier'])} | {', '.join(types)} | `{p['template']}` | {qs.replace('|', '\\|')} |")
        out.append("")
    open(os.path.join(ROOT, "BLUEPRINT.md"), "w").write("\n".join(out) + "\n")
    print("wrote BLUEPRINT.md")


if __name__ == "__main__":
    main()
